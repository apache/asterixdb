import { Injectable } from '@angular/core';
import { HttpClient, HttpErrorResponse, HttpHeaders } from '@angular/common/http';
import { Observable, of } from 'rxjs';
import { catchError, map } from 'rxjs/operators';
import { environment } from '../../../environments/environment';

function validationUrl(): string {
    if (environment.production) {
        const host = self.location.host.split(':')[0];
        return 'http://' + host + ':19002/admin/requests/running';
    }
    return '/admin/requests/running';
}

export type CredentialCheck = 'ok' | 'unauthorized' | 'error';

@Injectable({ providedIn: 'root' })
export class AuthService {
    private authHeader: string | null = null;
    private username: string | null = null;

    constructor(private http: HttpClient) {}

    setCredentials(username: string, password: string): void {
        this.username = username;
        this.authHeader = 'Basic ' + btoa(username + ':' + password);
    }

    getAuthHeader(): string | null {
        return this.authHeader;
    }

    getUsername(): string | null {
        return this.username;
    }

    hasCredentials(): boolean {
        return this.authHeader !== null;
    }

    clear(): void {
        this.authHeader = null;
        this.username = null;
    }

    /**
     * Probes the server with the supplied credentials. The interceptor leaves
     * the Authorization header alone when one is already set, so this request
     * uses exactly the credentials we are validating, regardless of any
     * previously stored header.
     */
    check(username: string, password: string): Observable<CredentialCheck> {
        const probe = 'Basic ' + btoa(username + ':' + password);
        const headers = new HttpHeaders({ Authorization: probe });
        return this.http.get(validationUrl(), { headers, observe: 'response' }).pipe(
            map(() => 'ok' as CredentialCheck),
            catchError((err: HttpErrorResponse) => {
                if (err.status === 401 || err.status === 403) {
                    return of('unauthorized' as CredentialCheck);
                }
                return of('error' as CredentialCheck);
            })
        );
    }
}
