import { ChangeDetectorRef, Component } from '@angular/core';
import { MatDialogRef } from '@angular/material/dialog';
import { AuthService } from '../shared/services/auth.service';

export interface LoginDialogResult {
    username: string;
    password: string;
}

@Component({
    standalone: false,
    selector: 'awc-login-dialog',
    templateUrl: 'login-dialog.component.html',
    styleUrls: ['login-dialog.component.scss']
})
export class LoginDialogComponent {
    username = '';
    password = '';
    errorMessage: string | null = null;
    submitting = false;

    constructor(
        public dialogRef: MatDialogRef<LoginDialogComponent, LoginDialogResult>,
        private auth: AuthService,
        private cdr: ChangeDetectorRef
    ) {
        this.dialogRef.disableClose = true;
    }

    onSubmit(): void {
        if (this.submitting) {
            return;
        }
        if (!this.username || !this.password) {
            this.errorMessage = 'Username and password are required.';
            return;
        }
        this.submitting = true;
        this.errorMessage = null;
        this.auth.check(this.username, this.password).subscribe(result => {
            if (result === 'ok') {
                this.dialogRef.close({ username: this.username, password: this.password });
                return;
            }
            this.submitting = false;
            this.errorMessage = result === 'unauthorized'
                ? 'Invalid username or password.'
                : 'Could not reach the server. Please try again.';
            this.cdr.detectChanges();
        });
    }
}
