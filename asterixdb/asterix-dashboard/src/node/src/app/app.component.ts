import { ChangeDetectorRef, Component, OnInit } from '@angular/core';
import { MatDialog } from '@angular/material/dialog';
import { AuthService } from './shared/services/auth.service';
import { LoginDialogComponent, LoginDialogResult } from './dashboard/login-dialog.component';

/*
 * Root component
 * Defines AsterixDB Dashboard application's layout
 */
@Component({
    standalone: false,
    selector: 'awc-root',
    templateUrl: './app.component.html',
    styleUrls: ['./app.component.scss']
})

export class AppComponent implements OnInit {
    title = 'Asterix DB Web Console';
    ready = false;

    constructor(private dialog: MatDialog, private auth: AuthService, private cdr: ChangeDetectorRef) {}

    ngOnInit(): void {
        if (this.auth.hasCredentials()) {
            this.ready = true;
        } else {
            this.promptForCredentials();
        }
    }

    private promptForCredentials(): void {
        const ref = this.dialog.open<LoginDialogComponent, void, LoginDialogResult>(LoginDialogComponent, {
            width: '380px',
            disableClose: true,
            hasBackdrop: true
        });
        ref.afterClosed().subscribe(result => {
            if (result) {
                this.auth.setCredentials(result.username, result.password);
                this.ready = true;
                this.cdr.detectChanges();
            }
        });
    }
}
